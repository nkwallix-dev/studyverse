function rectangle(raw,page){
 const [x,y,w,h]=raw.split(',').map(Number);
 const [W,H]=dimensions[page];
 if(![x,y,w,h].every(Number.isFinite)||x<0||y<0||w<8||h<8||x+w>W+2||y+h>H+2)
  throw Error('Bad original screenshot crop '+page+': '+raw);
 return {page,x,y,w,h,W,H};
}
function slices(raw,page){
 return raw?raw.split('+').filter(Boolean).map(r=>rectangle(r,page)):[];
}
function add(page,number,common,parts){
 if(crops[number])throw Error('Duplicate book crop '+number);
 const boxes=[...slices(common,page),...slices(parts,page)];
 if(!boxes.length)throw Error('Empty book crop '+number);
 crops[number]=Object.freeze(boxes);
}
function set(page,group,common,parts){
 for(const spec of parts.split(';')){
  if(!spec.trim())continue;
  const cut=spec.indexOf(':');
  if(cut<0)throw Error('Expected suffix:rectangle '+spec);
  const suffix=spec.slice(0,cut),rectangleList=spec.slice(cut+1);
  add(page,group+(suffix==='*'?'':suffix),common,rectangleList);
 }
}
